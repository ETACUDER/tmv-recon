# ---- Ledger-entry flag sets ----
# Sign convention recap:
#   IDP=Yes + AMOUNT negative -> Dr
#   IDP=No  + AMOUNT positive -> Cr
# Voucher balances when sum(AMOUNT) across all entries == 0.

