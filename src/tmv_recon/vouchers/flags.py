def round_off_flags(dr: bool) -> list[tuple[str, str]]:
    """ROUND OFF entry flags. dr=True means we lost (Dr); dr=False means we gained (Cr)."""
    base = list(LEDGER_FLAGS_PARTY_DR if dr else LEDGER_FLAGS_INCOME_CR)
    # ROUND OFF is never a party ledger.
    return [(k, "No" if k == "ISPARTYLEDGER" else v) for k, v in base]
